package wbsdk

// Ptr 返回 v 的指针。
//
// 本库所有「局部更新」的请求体都用指针区分**「不改」与「改成零值」**：
// nil = 服务端保持原值；指向零值 = 真的把它改成零值（例如清空一个邮箱地址）。
// 没有这个助手的话，清空密码得先声明一个临时变量，写起来很别扭：
//
//	patch := wbsdk.WatchdogMailPatch{Password: wbsdk.Ptr("")} // 清空已存的密码
//
// 用它构造指针时注意**别复用同一个指针**：多个字段指向同一个变量会让改动
// 互相覆盖。每处都调一次 Ptr(...) 即可。
func Ptr[T any](v T) *T { return &v }
